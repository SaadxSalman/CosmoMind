_TEMPLATES = {
    "lightcurve": _LIGHTCURVE_TPL,
    "spectrum": _SPECTRUM_TPL,
    "lookup": _LOOKUP_TPL,
    "orbit": _ORBIT_TPL,
}


@dataclass
class GenerationResult:
    code: str
    explanation: str
    intent: str
    valid: bool = False
    errors: list[str] = field(default_factory=list)


_OBJ_RE = re.compile(
    r"\b(?:HD\s*\d+\s*[b-z]?|Kepler-\d+\s*[b-z]?|KOI-\d+|TOI-\d+\s*[b-z]?|"
    r"WASP-\d+\s*[b-z]?|TRAPPIST-1(?:\s*[b-z])?|GJ\s*\d+|Alpha\s+Centauri|"
    r"Proxima\s+Centauri|Betelgeuse|Rigel|Sirius|Procyon|Arcturus|Aldebaran|"
    r"Vega|Capella|Rigel|Polaris|Cygnus\s+X-1)\b",
    re.I,
)


def classify_intent(request: str) -> str:
    r = request.lower()
    if any(k in r for k in ("light curve", "lightcurve", "plot", "chart")):
        return "lightcurve"
    if "spectrum" in r or "spectroscopic" in r:
        return "spectrum"
    if any(k in r for k in ("orbit", "orbital", "period", "eccentricity")):
        return "orbit"
    return "lookup"


def extract_object(request: str) -> str:
    m = _OBJ_RE.search(request)
    return m.group(0).strip() if m else "HD 189733 b"


def _safe_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").lower() or "obj"


from cosmo_mind.codegen.validation import ValidationResult, ast_check
from cosmo_mind.config import get_settings
from cosmo_mind.utils.logging import get_logger

log = get_logger("cosmo_mind.codegen")


class AstropyCodeGenerator:
    """Generates & validates Astropy/astroquery Python from a request."""

    def __init__(self, llm: LLMBackend | None = None) -> None:
        self.llm = llm

    def generate(
        self, request: str, context: str | None = None, use_llm: bool | None = None
    ) -> GenerationResult:
        """Produce validated Python code for *request*."""
        if use_llm is None:
            use_llm = get_settings().use_openai and bool(self.llm)
        if use_llm and context:
            result = self._generate_llm(request, context)
        elif use_llm:
            result = self._generate_llm(request)
        else:
            result = self._generate_template(request, context)
        vr = ast_check(result.code)
        result.valid = vr.ok
        result.errors = vr.errors
        if get_settings().cosmo_enable_code_sandbox:
            sr = _execute_sandbox(result.code)
            result.errors.extend(sr.errors)
            result.valid = result.valid and sr.ok
        return result

    def _generate_template(self, request: str, context: str | None) -> GenerationResult:
        intent = classify_intent(request)
        obj = extract_object(request)
        safe = _safe_name(obj)
        tpl = _TEMPLATES.get(intent, _TEMPLATES["lookup"])
        code = tpl.format(object=obj, safe=safe)
        expl = (
            f"Generated a runnable `{intent}` script for **{obj}** "
            "using astropy + astroquery. It fetches live data from SIMBAD / "
            "VizieR / NASA Exoplanet Archive and is syntactically validated."
        )
        return GenerationResult(code=code, explanation=expl, intent=intent)

    def _generate_llm(self, request: str, context: str | None = None) -> GenerationResult:
        sys_prompt = (
            "You are CosmoMind's code synthesizer. Write ONLY a single, runnable "
            "Python code block (fenced ```python) using astropy, astroquery and "
            "numpy/matplotlib. No prose outside the block. If a coordinate or "
            "object is mentioned, query the relevant live catalog. "
            "The code must be self-contained and import cleanly."
        )
        prompt = (
            f"Request: {request}\n"
            + (f"Context: {context}\n" if context else "")
        )
        llm = self.llm or _default_llm()
        res = llm.chat(
            [ChatMessage("system", sys_prompt), ChatMessage("user", prompt)],
            tools=None,
        )
        code = _extract_fenced(res.text or "")
        if not code:
            # fall back to template if the LLM refuses to emit code
            return self._generate_template(request, context)
        expl = f"LLM-synthesised Python for: {request}"
        return GenerationResult(code=code, explanation=expl, intent=classify_intent(request))


def _default_llm() -> "LLMBackend | None":
    from cosmo_mind.llm.chat import get_llm

    try:
        return get_llm()
    except Exception:
        return None


def _extract_fenced(text: str) -> str:
    """Pull the contents of a ```python ... ``` block, else return whole text."""
    m = re.search(r"```python\s*(.*?)\s*```", text, re.DOTALL)
    if m:
        return m.group(1)
    return text.strip()


def _execute_sandbox(code: str) -> "ValidationResult":
    """Execute generated code in a subprocess to validate runtime behaviour."""
    import subprocess
    import sys

    try:
        proc = subprocess.run(
            [sys.executable, "-c", code],
            capture_output=True,
            text=True,
            timeout=15,
        )
        ok = proc.returncode == 0
        errs: list[str] = []
        if proc.stderr:
            errs.append(proc.stderr.strip()[:2000])
        if not ok:
            errs.append(f"exit code {proc.returncode}")
        return ValidationResult(ok=ok, errors=errs, stdout=proc.stdout)
    except subprocess.TimeoutExpired:
        return ValidationResult(ok=False, errors=["sandbox execution timed out"], stdout="")
    except Exception as e:
        return ValidationResult(ok=False, errors=[str(e)], stdout="")


def get_code_generator() -> AstropyCodeGenerator:
    return AstropyCodeGenerator(llm=_default_llm())


__all__ = ["GenerationResult", "AstropyCodeGenerator", "get_code_generator"]