_nea = NasaExoplanet()
row = _nea.query_object(obj)
if row is None:
    print("No NASA Exoplanet Archive result for", obj)
    raise SystemExit(0)

_period = float(row["pl_orbper"]) if "pl_orbper" in row.colnames else 1.0
